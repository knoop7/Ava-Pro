    private fun parse(packed: String): List<Pair<String, String>> {
        val lines = packed.lineSequence()
        val out = ArrayList<Pair<String, String>>(1400)
        for (line in lines) {
            if (line.isEmpty()) continue
            val tab = line.indexOf('\t')
            if (tab <= 0) continue
            val name = line.substring(0, tab)
            val hex = line.substring(tab + 1)
            val cp = hex.toInt(16)
            out.add("fa-$name" to Char(cp).toString())
        }
        return out
    }

