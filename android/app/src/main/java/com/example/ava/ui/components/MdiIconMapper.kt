    fun getIconResId(icon: String): Int = iconMap[icon] ?: R.drawable.mdi_power

    fun getIconResIdForState(icon: String, isActive: Boolean): Int {
        val iconName = icon.removePrefix("mdi:").replace("-", "_")
        val stateIconName = when {
            iconName.contains("lightbulb") && !iconName.contains("_off") -> {
                if (isActive) "mdi:lightbulb" else "mdi:lightbulb-off"
            }
            iconName.contains("light_switch") && !iconName.contains("_off") -> {
                if (isActive) "mdi:light-switch" else "mdi:light-switch-off"
            }
            iconName.contains("lock") && !iconName.contains("_open") -> {
                if (isActive) "mdi:lock-open" else "mdi:lock"
            }
            iconName.contains("door") && !iconName.contains("_open") -> {
                if (isActive) "mdi:door-open" else "mdi:door"
            }
            iconName.contains("garage") && !iconName.contains("_open") -> {
                if (isActive) "mdi:garage-open" else "mdi:garage"
            }
            iconName.contains("window") && !iconName.contains("_open") && !iconName.contains("_closed") -> {
                if (isActive) "mdi:window-open" else "mdi:window-closed"
            }
            else -> icon
        }
        return iconMap[stateIconName] ?: R.drawable.mdi_power
    }
